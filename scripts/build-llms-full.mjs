#!/usr/bin/env node
// Builds llms-full.txt: one self-contained briefing for LLMs/agents (AGENTS.md + key docs).
// Run `npm run llms`; CI does not require it, but keep it fresh when those docs change.
import { readFileSync, writeFileSync } from 'node:fs'

const parts = [
  ['AGENTS.md', 'Guide for AI coding agents'],
  ['README.md', 'README'],
  ['docs/ARCHITECTURE.md', 'Architecture'],
  ['docs/DATABASE.md', 'Database options and migrations'],
  ['CONTRIBUTING.md', 'Contributing and invariants'],
  ['SECURITY.md', 'Security policy'],
]
const header = `# ssERP: full briefing for LLMs and coding agents

Generated by scripts/build-llms-full.mjs from the files listed below. Short index: llms.txt.
Source: https://github.com/bemoshiur/Super-Simple-ERP-ssERP (MIT).
`
const body = parts
  .map(([file, title]) => `\n\n---\n\n<!-- ${file} -->\n# [${title}] ${file}\n\n${readFileSync(file, 'utf8').trim()}\n`)
  .join('')
writeFileSync('llms-full.txt', `${header}${body}`)
console.log(`llms-full.txt written (${Buffer.byteLength(header + body)} bytes)`)
